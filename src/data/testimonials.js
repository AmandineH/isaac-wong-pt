export function sortTestimonials(orderArray, testimonials_) {
  const orderMap = new Map(orderArray.map((key, index) => [key, index]));
  return testimonials_.sort(
    (a, b) => orderMap.get(a.key) - orderMap.get(b.key)
  );
}

